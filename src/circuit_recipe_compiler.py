"""Compile an elaborated PyRTL block to a Regrow-8 text recipe."""

from __future__ import annotations

import argparse
from collections import deque
from pathlib import Path
import re
import runpy
import sys

import pyrtl


_PRIMITIVES = {"~": "NOT", "&": "AND", "|": "OR", "^": "XOR", "r": "DFF"}


class RecipeError(ValueError):
    """A circuit cannot be represented as a Regrow-8 recipe."""


def _pin_names(ports):
    names = set()
    result = {}
    for port in ports:
        base = re.sub(r"[^A-Za-z0-9_.-]", "_", port.name)
        if not re.match(r"[A-Za-z_]", base):
            base = f"_{base}"
        bits = [base] if len(port) == 1 else [f"{base}{bit}" for bit in range(len(port))]
        for pin in bits:
            if pin in names:
                raise RecipeError(f"port {port.name!r} produces duplicate recipe pin {pin!r}")
            names.add(pin)
        result[port] = bits
    return result, names


class _Recipe:
    def __init__(self, block, inputs, reserved_names):
        self.drivers = {net.dests[0]: net for net in block.logic}
        self.names = dict(inputs)
        self.reserved_names = reserved_names
        self.registers = deque()
        self.constants = {}
        self.first_input = next(iter(inputs.values()))
        self.gate_index = 0

    def _new_name(self):
        while True:
            name = f"g{self.gate_index}"
            self.gate_index += 1
            if name not in self.reserved_names:
                return name

    def _constant(self, value, gates):
        if 0 not in self.constants:
            name = self.constants[0] = self._new_name()
            gates.append(f"  gate {name} XOR {self.first_input} {self.first_input}")
        if value and 1 not in self.constants:
            name = self.constants[1] = self._new_name()
            gates.append(f"  gate {name} NOT {self.constants[0]}")
        return self.constants[value]

    def _reference(self, wire, gates, pending):
        while (net := self.drivers.get(wire)) and net.op == "w":
            wire = net.args[0]
        if wire in self.names:
            return self.names[wire]
        if isinstance(wire, pyrtl.Const):
            return self._constant(wire.val, gates)
        if net is None:
            raise RecipeError(f"undriven wire {wire.name!r}")

        name = self.names[wire] = self._new_name()
        if net.op == "r":
            # Cut feedback at Q. Route the D input in the register's own group.
            self.registers.append((name, net))
        else:
            pending.append((name, net))
        return name

    def _drain(self, gates, pending):
        while pending:
            name, net = pending.pop()
            args = [self._reference(wire, gates, pending) for wire in net.args]
            if net.op == "n":
                intermediate = self._new_name()
                gates.append(f"  gate {intermediate} AND {' '.join(args)}")
                gates.append(f"  gate {name} NOT {intermediate}")
            else:
                primitive = _PRIMITIVES[net.op]
                gates.append(f"  gate {name} {primitive} {' '.join(args)}")

    def emit(self, inputs, outputs):
        lines = ["# Generated by Circuit Recipe Compiler", f"inputs {' '.join(inputs)}"]
        output_rows = []
        for pin, wire in outputs:
            gates = []
            pending = []
            name = self._reference(wire, gates, pending)
            self._drain(gates, pending)
            if gates:
                lines.extend(("", f"group out.{pin}", *gates))
            output_rows.append(f"output {pin} {name}")
        while self.registers:
            name, net = self.registers.popleft()
            gates = []
            self._drain(gates, [(name, net)])
            lines.extend(("", f"group reg.{name}", *gates))
        return "\n".join([*lines, "", *output_rows, ""])


def compile_block(block: pyrtl.Block) -> str:
    """Synthesize a PyRTL block and return a portable text recipe."""
    ports = list(block.wirevector_by_name.values())
    inputs = [wire for wire in ports if isinstance(wire, pyrtl.Input)]
    outputs = [wire for wire in ports if isinstance(wire, pyrtl.Output)]
    if not inputs or not outputs:
        raise RecipeError("a recipe needs at least one input and one output")
    if block.logic_subset("m@"):
        raise RecipeError("memory blocks require external ROM/RAM connected to pins")
    for register in block.wirevector_subset(pyrtl.Register):
        if register.reset_value not in (None, 0):
            raise RecipeError(f"register {register.name!r} has a nonzero initial value")

    pins, reserved = _pin_names([*inputs, *outputs])
    bit_block = pyrtl.synthesize(
        block=block, update_working_block=False, merge_io_vectors=False
    )
    # PyRTL's dependency order detects combinational loops before optimization.
    for _ in bit_block:
        pass
    pyrtl.optimize(block=bit_block)
    input_bits = {
        wire: pin for port in inputs for wire, pin in zip(bit_block.io_map[port], pins[port])
    }
    output_bits = [
        (pin, wire) for port in outputs for wire, pin in zip(bit_block.io_map[port], pins[port])
    ]
    return _Recipe(bit_block, input_bits, reserved).emit(input_bits.values(), output_bits)


def _compile_design(path: Path) -> str:
    old_path, old_argv = sys.path, sys.argv
    sys.path = [str(path.parent), *sys.path]
    sys.argv = [str(path)]
    try:
        with pyrtl.set_working_block(pyrtl.Block()):
            runpy.run_path(str(path), run_name="__main__")
            return compile_block(pyrtl.working_block())
    finally:
        sys.path, sys.argv = old_path, old_argv


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("design", type=Path, help="Python file that builds a PyRTL circuit")
    parser.add_argument("-o", "--out", type=Path, required=True, help="output .txt recipe")
    args = parser.parse_args(argv)
    try:
        design = args.design.resolve()
        if design == args.out.resolve():
            raise RecipeError("specify a different path for the output recipe")
        recipe = _compile_design(design)
        args.out.write_text(recipe, encoding="utf-8", newline="\n")
    except (OSError, RecipeError, pyrtl.PyrtlError) as error:
        parser.exit(1, f"crc: {error}\n")


if __name__ == "__main__":
    main()
